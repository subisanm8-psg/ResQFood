import React, { useState } from 'react';
import { Layers, ChevronDown, ChevronUp, Info, CheckCircle2, Truck, Clock } from 'lucide-react';
import { useAppStore } from '../../store/useAppStore';
import { EmptyState } from '../common/EmptyState';

export const IncomingMatchesPanel: React.FC = () => {
  const { matches, lots, requests, receivers, selectedProviderId } = useAppStore();

  const [expandedMatchId, setExpandedMatchId] = useState<string | null>(null);

  const providerMatches = matches.filter((m) => {
    const lot = lots.find((l) => l.id === m.lotId);
    return lot && lot.providerId === selectedProviderId && m.status !== 'Declined';
  });

  const getStatusChip = (status: string) => {
    switch (status) {
      case 'Delivered':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[10px] font-semibold bg-emerald-50 text-emerald-800 border border-emerald-200">
            <CheckCircle2 className="w-3 h-3" /> Delivered
          </span>
        );
      case 'In Transit':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[10px] font-semibold bg-amber-50 text-amber-800 border border-amber-200">
            <Truck className="w-3 h-3" /> In Transit
          </span>
        );
      default:
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[10px] font-semibold bg-blue-50 text-blue-800 border border-blue-200">
            <Clock className="w-3 h-3" /> Proposed / Assigned
          </span>
        );
    }
  };

  return (
    <div className="bg-white rounded-3xl border border-stone-200/80 shadow-card overflow-hidden">
      <div className="p-4 sm:p-5 border-b border-stone-100 flex items-center justify-between">
        <div>
          <h3 className="font-bold text-sm text-stone-900">Incoming Redistribution Matches</h3>
          <p className="text-xs text-stone-500">Receiver assignments generated by the multi-objective matcher</p>
        </div>
        <span className="text-xs font-semibold px-2.5 py-1 rounded-xl bg-primary-50 text-primary-800">
          {providerMatches.length} Active
        </span>
      </div>

      {providerMatches.length === 0 ? (
        <div className="p-6">
          <EmptyState
            icon={Layers}
            title="No matches assigned yet"
            description="When nearby receivers place food requests compatible with your surplus, they will appear here with score breakdowns."
          />
        </div>
      ) : (
        <div className="p-4 space-y-3">
          {providerMatches.map((match) => {
            const lot = lots.find((l) => l.id === match.lotId);
            const req = requests.find((r) => r.id === match.requestId);
            const receiver = req ? receivers.find((rec) => rec.id === req.receiverId) : undefined;
            const isExpanded = expandedMatchId === match.id;

            return (
              <div
                key={match.id}
                className="p-4 rounded-2xl border border-stone-200/80 bg-stone-50/50 hover:bg-stone-50 transition-colors space-y-3"
              >
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                  <div>
                    <div className="flex items-center gap-2">
                      <h4 className="font-bold text-xs text-stone-900">
                        {receiver?.name || 'Receiver Organization'}
                      </h4>
                      <span className="text-[10px] px-2 py-0.5 rounded-md bg-stone-100 text-stone-700 font-medium">
                        {receiver?.organizationType}
                      </span>
                    </div>
                    <p className="text-[11px] text-stone-500 mt-0.5">
                      Allocated: <span className="font-semibold text-primary-800">{match.quantityAllocated} {lot?.unit || 'portions'}</span> of "{lot?.itemName}"
                    </p>
                  </div>

                  <div className="flex items-center gap-2.5">
                    {getStatusChip(match.status)}
                    <div className="text-right">
                      <div className="text-[10px] text-stone-400 font-semibold uppercase">Match Score</div>
                      <div className="text-xs font-mono font-bold text-primary-800">
                        {(match.score * 100).toFixed(0)}%
                      </div>
                    </div>
                  </div>
                </div>

                {/* "Why this match?" accordion button */}
                <div className="pt-1 border-t border-stone-200/60 flex items-center justify-between">
                  <div className="text-[11px] text-stone-500">
                    Travel distance: <span className="font-semibold text-stone-800">{match.distanceKm} km</span> &bull; Transit ETA: <span className="font-semibold text-stone-800">{match.etaMinutes} mins</span>
                  </div>

                  <button
                    onClick={() => setExpandedMatchId(isExpanded ? null : match.id)}
                    className="text-[11px] font-semibold text-primary-700 hover:text-primary-900 flex items-center gap-1 transition-colors"
                  >
                    <Info className="w-3.5 h-3.5" />
                    <span>Why this match?</span>
                    {isExpanded ? <ChevronUp className="w-3.5 h-3.5" /> : <ChevronDown className="w-3.5 h-3.5" />}
                  </button>
                </div>

                {/* Expanded breakdown */}
                {isExpanded && (
                  <div className="p-3 bg-white rounded-xl border border-stone-200 text-xs space-y-2 animate-in fade-in duration-150">
                    <div className="font-semibold text-[11px] text-stone-800">
                      Algorithmic Score Breakdown:
                    </div>
                    <div className="grid grid-cols-3 gap-2 text-[11px]">
                      <div className="p-2 bg-stone-50 rounded-lg">
                        <div className="text-stone-500 text-[10px]">Expiry Urgency ({match.scoreBreakdown.wWaste * 100}%)</div>
                        <div className="font-bold text-rose-700 font-mono mt-0.5">
                          {(match.scoreBreakdown.expiryPressure * 100).toFixed(0)}%
                        </div>
                      </div>
                      <div className="p-2 bg-stone-50 rounded-lg">
                        <div className="text-stone-500 text-[10px]">Proximity ({match.scoreBreakdown.wDist * 100}%)</div>
                        <div className="font-bold text-blue-700 font-mono mt-0.5">
                          {((1 - match.scoreBreakdown.distanceNormalized) * 100).toFixed(0)}%
                        </div>
                      </div>
                      <div className="p-2 bg-stone-50 rounded-lg">
                        <div className="text-stone-500 text-[10px]">Demand Fit ({match.scoreBreakdown.wDemand * 100}%)</div>
                        <div className="font-bold text-emerald-700 font-mono mt-0.5">
                          {(match.scoreBreakdown.quantityFit * 100).toFixed(0)}%
                        </div>
                      </div>
                    </div>
                    <p className="text-[10px] text-stone-400">
                      Calculated priority formula: wWaste &times; expiryPressure + wDist &times; (1 - distNorm) + wDemand &times; quantityFit
                    </p>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
